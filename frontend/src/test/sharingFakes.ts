/**
 * Fakes for the share bridge.
 *
 * Like the privacy fakes, these drive a real `ApiClient` over a fake `fetch`,
 * so the tests exercise the real request shapes, headers and error envelope
 * rather than a hand-written stub layer.
 *
 * The public-viewer fake is different in one important way: it serves **real
 * ciphertext**, produced by `app/services/sharing/crypto.py` and committed as
 * `src/features/sharing/testSupport/shareVector.json`. The viewer decrypts it in
 * the browser with WebCrypto, so a test that opens a share proves the whole
 * cross-language path — server encryption, URL-fragment key, HKDF derivation,
 * AES-GCM with Associated Data — and not just that a component rendered.
 */

