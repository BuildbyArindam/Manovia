export interface ShareFake {
  client: ApiClient;
  /** Every create body the component sent, in order. */
  creates: CreateShareBody[];
  /** Every preview body the component sent, in order. */
  previews: ShareSelectionBody[];
  /** The preference values the component saved. */
  preferences: boolean[];
  /** The ids the component revoked, plus one entry per revoke-all. */
  revokes: string[];
  revokeAllCalls: number;
  /** What the fake serves. */
  options: ShareOptions;
  preview: PreviewOut;
  shares: ShareSummary[];
  audit: AuditOut;
  /** Force the next preview (and preference) call to fail with this envelope. */
  failWith: { status: number; code: string; message: string } | null;
  /** Force only `POST /shares` to fail, leaving the preview working. */
  failCreate: { status: number; code: string; message: string } | null;
  /** How many times the public open was called (it spends a view). */
  opens: number;
  /** The passcodes the viewer sent. */
  passcodes: string[];
  /** Force the public *status* call to fail (a dead link). */
  failPublic: { status: number; code: string; message: string } | null;
  /** Force only `POST /open` to fail (a wrong passcode, a lock, a throttle). */
  failOpen: { status: number; code: string; message: string } | null;
  status: PublicStatusOut;
  opened: OpenOut;
}

const json = (body: unknown, status = 200): Response =>
  new Response(JSON.stringify(body), {
    status,
    headers: { "Content-Type": "application/json" },
  });

const failure = (spec: { status: number; code: string; message: string }): Response =>
  new Response(
    JSON.stringify({ error: { code: spec.code, message: spec.message, request_id: "req-fake" } }),
    {
      status: spec.status,
      headers: { "Content-Type": "application/json", "X-Request-ID": "req-fake" },
    },
  );

/** A client that answers the owner endpoints (and, optionally, the public ones). */
export function makeShareFake(
  options: {
    options?: ShareOptions;
    preview?: PreviewOut;
    shares?: ShareSummary[];
    audit?: AuditOut;
    authenticated?: boolean;
    /** Also answer `/public/shares/...`, for a single client in one test. */
    public?: boolean;
  } = {},
): ShareFake {
  const store = new MemoryTokenStore();
  if (options.authenticated !== false) {
    store.write({
      accessToken: "access-token",
      refreshToken: "refresh-token",
      tokenType: "bearer",
      expiresAt: Date.now() + 3_600_000,
    });
  }

  const fake: ShareFake = {
    client: new ApiClient({ tokens: store, baseUrl: "/api/v1" }),
    creates: [],
    previews: [],
    preferences: [],
    revokes: [],
    revokeAllCalls: 0,
    options: options.options ?? shareOptions(),
    preview: options.preview ?? previewOut(),
    shares: options.shares ?? [shareSummary()],
    audit: options.audit ?? auditOut(),
    failWith: null,
    failCreate: null,
    opens: 0,
    passcodes: [],
    failPublic: null,
    failOpen: null,
    status: publicStatus(),
    opened: openOut(),
  };

  fake.client = new ApiClient({
    tokens: store,
    baseUrl: "/api/v1",
    fetchImpl: async (input, init) => {
      const url = String(input);
      const method = init?.method ?? "GET";
      const body =
        init?.body === undefined
          ? null
          : (JSON.parse(String(init.body)) as Record<string, unknown>);

      if (url.includes("/public/shares/")) {
        const isOpen = url.endsWith("/open") && method === "POST";
        if (isOpen && fake.failOpen !== null) {
          fake.opens += 1;
          fake.passcodes.push(String(body?.passcode ?? ""));
          return failure(fake.failOpen);
        }
        if (!isOpen && fake.failPublic !== null) {
          return failure(fake.failPublic);
        }
        if (isOpen) {
          fake.opens += 1;
          fake.passcodes.push(String(body?.passcode ?? ""));
          return json(fake.opened);
        }
        return json(fake.status);
      }

      if (url.endsWith("/shares/options")) {
        return json(fake.options);
      }
      if (url.endsWith("/shares/preferences") && method === "POST") {
        if (fake.failWith !== null) {
          return failure(fake.failWith);
        }
        const enabled = Boolean(body?.enabled);
        fake.preferences.push(enabled);
        fake.options = { ...fake.options, enabled };
        return json({
          enabled,
          deployment_enabled: true,
          updated_at: null,
        } satisfies PreferenceOut);
      }
      if (url.endsWith("/shares/preview") && method === "POST") {
        if (fake.failWith !== null) {
          return failure(fake.failWith);
        }
        fake.previews.push(body as unknown as ShareSelectionBody);
        return json(fake.preview);
      }
      if (url.endsWith("/shares") && method === "POST") {
        if (fake.failCreate !== null) {
          return failure(fake.failCreate);
        }
        if (fake.failWith !== null) {
          return failure(fake.failWith);
        }
        fake.creates.push(body as unknown as CreateShareBody);
        return json(createdShare(), 201);
      }
      if (url.endsWith("/shares/revoke-all") && method === "POST") {
        fake.revokeAllCalls += 1;
        const ids = fake.shares
          .filter((share) => share.status === "active")
          .map((share) => share.id);
        fake.shares = fake.shares.map((share) =>
          share.status === "active"
            ? { ...share, status: "revoked", revoked_at: "2026-10-19T14:00:00Z" }
            : share,
        );
        return json({ revoked: ids.length, ids });
      }
      if (url.endsWith("/shares") && method === "GET") {
        return json(fake.shares);
      }
      if (url.endsWith("/audit")) {
        return json(fake.audit);
      }
      if (url.endsWith("/revoke") && method === "POST") {
        const shareId = url.split("/").slice(-2, -1)[0] ?? "";
        fake.revokes.push(shareId);
        fake.shares = fake.shares.map((share) =>
          share.id === shareId
            ? { ...share, status: "revoked", revoked_at: "2026-10-19T14:00:00Z" }
            : share,
        );
        return json({ id: shareId, revoked_at: "2026-10-19T14:00:00Z", status: "revoked" });
      }
      if (/\/shares\/[0-9a-f-]{36}$/.test(url)) {
        const shareId = url.split("/").pop() ?? "";
        const found = fake.shares.find((share) => share.id === shareId);
        return found === undefined
          ? failure({ status: 404, code: "share_not_found", message: "Not found" })
          : json(found);
      }
      return failure({ status: 404, code: "not_found", message: "Not found" });
    },
  });

  return fake;
}
