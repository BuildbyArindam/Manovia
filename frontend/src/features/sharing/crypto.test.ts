/**
 * The browser half of the share encryption, checked against the server half.
 *
 * The vector below was produced by `app/services/sharing/crypto.py` (the same
 * module that encrypts a real share), so the first two tests are the actual
 * cross-language proof: if the TypeScript derivation and the Python derivation
 * ever disagree, a shared document stops opening and these fail first — rather
 * than a person typing a correct passcode and being told it is wrong.
 *
 * Reproduce the vector with:
 *
 *   cd backend && python - <<'PY'
 *   from app.services.sharing import crypto
 *   from app.models.share import share_aad
 *   secret = b"manovia-share-vector-secret-key!"
 *   key = crypto.derive_key(secret=secret, passcode="483920", token=VECTOR.token)
 *   print(key.hex())
 *   PY
 */

import { describe, expect, it } from "vitest";

import {
  ALGORITHM,
  HKDF_INFO,
  KEY_BYTES,
  NONCE_BYTES,
  SECRET_BYTES,
  ShareCryptoUnavailable,
  ShareDecryptFailed,
  decryptDocument,
  decryptText,
  deriveShareKey,
  deriveShareKeyBits,
  fromBase64Url,
  keyFromUrl,
  toBase64Url,
} from "./crypto";

/** Generated by `app/services/sharing/crypto.py`; see the header comment. */
const VECTOR = {
  secret: "bWFub3ZpYS1zaGFyZS12ZWN0b3Itc2VjcmV0LWtleSE",
  passcode: "483920",
  token: "vectorToken0123456789",
  keyHex: "f9349a15e94dd7e149f33b5abd6e6cc1a3e1b803533610c3912089a92e516eb3",
  aad: "manovia.share.v1.vectorToken0123456789.payload",
  plaintext: '{"kind":"manovia.appointment-summary","note":"cross-language vector"}',
  ciphertext:
    "sPxnNJZp8kRDjoWPZuuIKcyhtcTrTb6IFCMchehO8Ee5oj9WVkqzCVF6G0xQTtklZfrtPRE5HWVGJT9qlH9jO8HGiQ51P5j1-Tee-mhU2MO3pL0nbA",
  nonce: "QomQbc4MBccMRema",
} as const;

function hex(bytes: Uint8Array): string {
  return [...bytes].map((byte) => byte.toString(16).padStart(2, "0")).join("");
}

function aDocument(overrides: Partial<Record<string, string>> = {}) {
  return {
    ciphertext: VECTOR.ciphertext,
    nonce: VECTOR.nonce,
    aad: VECTOR.aad,
    algorithm: ALGORITHM,
    ...overrides,
  };
}

describe("the derivation matches the server", () => {
  it("derives the exact 32 bytes Python derives", async () => {
    const bits = await deriveShareKeyBits(VECTOR);
    expect(hex(bits)).toBe(VECTOR.keyHex);
    expect(bits.byteLength).toBe(KEY_BYTES);
  });

  it("decrypts a document the server encrypted", async () => {
    const key = await deriveShareKey(VECTOR);
    const text = await decryptText(key, aDocument());
    expect(text).toBe(VECTOR.plaintext);
    expect(JSON.parse(text).note).toBe("cross-language vector");
  });

  it("derives a different key for a different passcode, secret or token", async () => {
    const base = hex(await deriveShareKeyBits(VECTOR));
    expect(hex(await deriveShareKeyBits({ ...VECTOR, passcode: "483921" }))).not.toBe(base);
    expect(hex(await deriveShareKeyBits({ ...VECTOR, token: "vectorToken0123456780" }))).not.toBe(
      base,
    );
    expect(
      hex(
        await deriveShareKeyBits({
          ...VECTOR,
          secret: toBase64Url(new Uint8Array(SECRET_BYTES).fill(7)),
        }),
      ),
    ).not.toBe(base);
  });

  it("uses the documented HKDF parameters", () => {
    expect(HKDF_INFO).toBe("manovia.share.v1.key");
    expect(ALGORITHM).toBe("A256GCM");
    expect(SECRET_BYTES).toBe(32);
    expect(NONCE_BYTES).toBe(12);
  });

  it("hands back a key that cannot be read out of WebCrypto", async () => {
    const key = await deriveShareKey(VECTOR);
    expect(key.extractable).toBe(false);
    expect(key.usages).toEqual(["decrypt"]);
    await expect(crypto.subtle.exportKey("raw", key)).rejects.toBeTruthy();
  });
});

describe("one refusal for every way to be wrong", () => {
  it("does not distinguish a wrong passcode from a changed byte", async () => {
    const key = await deriveShareKey(VECTOR);
    const wrongKey = await deriveShareKey({ ...VECTOR, passcode: "000000" });
    const flipped = new Uint8Array(fromBase64Url(VECTOR.ciphertext));
    const firstByte = flipped[0] ?? 0;
    flipped[0] = firstByte ^ 0x01;

    const attempts = [
      ["wrong passcode", wrongKey, aDocument()],
      ["flipped ciphertext byte", key, aDocument({ ciphertext: toBase64Url(flipped) })],
      [
        "wrong AAD (another document slot)",
        key,
        aDocument({ aad: VECTOR.aad.replace("payload", "pdf") }),
      ],
      ["wrong AAD (another share)", key, aDocument({ aad: "manovia.share.v1.otherToken.payload" })],
      ["empty AAD", key, aDocument({ aad: "" })],
      ["truncated ciphertext", key, aDocument({ ciphertext: toBase64Url(flipped.slice(0, 40)) })],
    ] as const;

    const messages = new Set<string>();
    for (const [, attemptKey, attemptDocument] of attempts) {
      await expect(decryptDocument(attemptKey, attemptDocument)).rejects.toBeInstanceOf(
        ShareDecryptFailed,
      );
      try {
        await decryptDocument(attemptKey, attemptDocument);
      } catch (error) {
        expect((error as ShareDecryptFailed).reason).toBe("decrypt-failed");
        messages.add((error as Error).message);
      }
    }
    expect(messages.size).toBe(1);
  });

  it("reports a malformed link as malformed, not as a wrong passcode", async () => {
    const key = await deriveShareKey(VECTOR);
    const malformed = [
      aDocument({ nonce: toBase64Url(new Uint8Array(11)) }),
      aDocument({ nonce: toBase64Url(new Uint8Array(13)) }),
      aDocument({ ciphertext: toBase64Url(new Uint8Array(15)) }),
      aDocument({ ciphertext: "" }),
      aDocument({ ciphertext: "not base64!!" }),
      aDocument({ algorithm: "A128GCM" }),
    ];
    for (const candidate of malformed) {
      await expect(decryptDocument(key, candidate)).rejects.toMatchObject({
        reason: "malformed",
      });
    }
  });

  it("refuses a secret of the wrong length before touching the ciphertext", async () => {
    for (const secret of ["", "   ", toBase64Url(new Uint8Array(31)), "!!!!", "a"]) {
      await expect(deriveShareKeyBits({ ...VECTOR, secret })).rejects.toMatchObject({
        reason: "malformed",
      });
    }
  });

  it("says so when there is no passcode or no token to derive from", async () => {
    await expect(deriveShareKey({ ...VECTOR, passcode: "  " })).rejects.toBeInstanceOf(
      ShareCryptoUnavailable,
    );
    await expect(deriveShareKey({ ...VECTOR, token: "" })).rejects.toBeInstanceOf(
      ShareCryptoUnavailable,
    );
  });
});

describe("the wire format", () => {
  it("round-trips unpadded base64url", () => {
    for (const length of [1, 12, 16, 32, 33, 256]) {
      const bytes = new Uint8Array(length);
      crypto.getRandomValues(bytes);
      const encoded = toBase64Url(bytes);
      expect(encoded).not.toContain("=");
      expect(encoded).toMatch(/^[A-Za-z0-9_-]+$/);
      expect(hex(fromBase64Url(encoded))).toBe(hex(bytes));
    }
  });

  it("rejects anything that is not unpadded base64url", () => {
    for (const value of ["", "   ", "a===b", "ab+cd", "ab/cd", "not base64!", "🙂"]) {
      expect(() => fromBase64Url(value)).toThrow(ShareDecryptFailed);
    }
  });

  it("encodes every byte value without the URL-unsafe characters", () => {
    const all = new Uint8Array(256);
    for (let index = 0; index < 256; index += 1) {
      all[index] = index;
    }
    const encoded = toBase64Url(all);
    expect(encoded).not.toContain("+");
    expect(encoded).not.toContain("/");
    expect(hex(fromBase64Url(encoded))).toBe(hex(all));
  });
});

describe("reading the key out of a link", () => {
  it("finds the fragment on an absolute or a relative URL", () => {
    expect(keyFromUrl(`https://manovia.app/s/${VECTOR.token}#k=${VECTOR.secret}`)).toBe(
      VECTOR.secret,
    );
    expect(keyFromUrl(`/s/${VECTOR.token}#k=${VECTOR.secret}`)).toBe(VECTOR.secret);
    expect(
      keyFromUrl(new URL(`/s/${VECTOR.token}#k=${VECTOR.secret}`, "https://manovia.app")),
    ).toBe(VECTOR.secret);
  });

  it("ignores other fragment parameters and survives a missing one", () => {
    expect(keyFromUrl(`/s/${VECTOR.token}#lang=hi&k=${VECTOR.secret}`)).toBe(VECTOR.secret);
    expect(keyFromUrl(`/s/${VECTOR.token}#k=${VECTOR.secret}&lang=hi`)).toBe(VECTOR.secret);
    expect(keyFromUrl(`/s/${VECTOR.token}`)).toBeNull();
    expect(keyFromUrl(`/s/${VECTOR.token}#`)).toBeNull();
    expect(keyFromUrl(`/s/${VECTOR.token}#lang=hi`)).toBeNull();
    expect(keyFromUrl(`/s/${VECTOR.token}#k=`)).toBeNull();
    expect(keyFromUrl("::::not a url::::")).toBeNull();
  });

  it("never puts the key in the path or the query", () => {
    const url = `/s/${VECTOR.token}#k=${VECTOR.secret}`;
    const [beforeFragment] = url.split("#");
    expect(beforeFragment).toBe(`/s/${VECTOR.token}`);
    expect(beforeFragment).not.toContain(VECTOR.secret);
  });
});
