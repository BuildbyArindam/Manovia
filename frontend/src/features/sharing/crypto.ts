/**
 * Browser-side decryption for a shared appointment summary (Day 47).
 *
 * The server stores ciphertext and nothing else: the 256-bit content key is
 * derived from a secret that lives **only in the URL fragment** (`/s/<token>#k=…`)
 * plus the passcode the owner gave out separately. Fragments are not sent to a
 * server, so the secret never appears in an access log, a proxy log or a
 * `Referer` header — which is why the link is split this way instead of being
 * one long token.
 *
 * The derivation is the server's, exactly:
 *
 *   ikm  = url_key || 0x00 || utf8(passcode)
 *   salt = SHA-256(token)
 *   info = "manovia.share.v1.key"
 *   HKDF-SHA256 -> 32 bytes -> AES-GCM key
 *
 * `OpenOut.key_derivation` carries that sentence so a reviewer can check the two
 * implementations agree without reading either one, and
 * `src/features/sharing/crypto.test.ts` pins it against a vector generated by
 * `app/services/sharing/crypto.py`.
 *
 * Each document also arrives with its Associated Data (`manovia.share.v1.<token>
 * .<name>`), so ciphertext lifted out of another share — or the PDF slot pasted
 * into the FHIR slot of the same share — fails to authenticate instead of
 * rendering somebody else's document.
 *
 * WHAT THIS DOES NOT PROTECT AGAINST
 *   - Whoever has the link *and* the passcode. That is the person it was sent to.
 *   - A compromised browser or extension on the viewer's machine while the
 *     document is open: the plaintext is in memory and the derived key is
 *     reachable from the page.
 *   - Loss. There is no copy of the key anywhere. Closing the tab drops it, and
 *     the owner cannot re-open their own link later — which is the point.
 */

/** AES-256-GCM, the value the server puts in `algorithm`. */
export const ALGORITHM = "A256GCM";
export const KEY_BYTES = 32;
export const KEY_LENGTH_BITS = 256;
export const NONCE_BYTES = 12;
export const SECRET_BYTES = 32;
/** HKDF `info`, shared with `app/services/sharing/crypto.py`. */
export const HKDF_INFO = "manovia.share.v1.key";
/** The tag length GCM appends; a ciphertext shorter than this cannot be one. */
export const TAG_BYTES = 16;
/** The fragment parameter that carries the key. */
export const KEY_FRAGMENT_PARAM = "k";

export class ShareCryptoUnavailable extends Error {
  constructor(message: string, options?: { cause?: unknown }) {
    super(message, options);
    this.name = "ShareCryptoUnavailable";
  }
}

/**
 * One refusal, for every way of being wrong.
 *
 * `no-key` is about the URL the viewer is holding (it has no fragment), which
 * they can see for themselves without asking the server. Everything else —
 * a wrong passcode, a wrong key, a changed byte, a mismatched AAD — collapses
 * into `decrypt-failed`, because telling them apart would be an oracle.
 */
export type ShareDecryptReason = "no-key" | "malformed" | "decrypt-failed";

export class ShareDecryptFailed extends Error {
  readonly reason: ShareDecryptReason;

  constructor(reason: ShareDecryptReason) {
    super(`this share cannot be opened (${reason})`);
    this.name = "ShareDecryptFailed";
    this.reason = reason;
  }
}

function subtle(): SubtleCrypto {
  const cryptoObject = globalThis.crypto;
  if (cryptoObject?.subtle === undefined) {
    throw new ShareCryptoUnavailable(
      "this browser has no WebCrypto, so a shared document cannot be decrypted here",
    );
  }
  return cryptoObject.subtle;
}

/**
 * Unpadded base64url to bytes.
 *
 * Strict on purpose: `atob` silently discards characters outside its alphabet,
 * so a truncated or mangled key would decode into *something* and then fail as
 * "wrong passcode" — the most confusing possible answer. A malformed key is
 * reported as malformed.
 */
export function fromBase64Url(value: string): Uint8Array {
  const text = value.trim();
  if (text === "") {
    throw new ShareDecryptFailed("malformed");
  }
  if (!/^[A-Za-z0-9_-]+$/.test(text)) {
    throw new ShareDecryptFailed("malformed");
  }
  const standard = text.replace(/-/g, "+").replace(/_/g, "/");
  const padded = standard + "=".repeat((4 - (standard.length % 4)) % 4);
  let binary: string;
  try {
    binary = atob(padded);
  } catch {
    throw new ShareDecryptFailed("malformed");
  }
  const bytes = new Uint8Array(binary.length);
  for (let index = 0; index < binary.length; index += 1) {
    bytes[index] = binary.charCodeAt(index);
  }
  return bytes;
}

/** Bytes to unpadded base64url: the form a URL fragment can carry. */
export function toBase64Url(bytes: Uint8Array): string {
  let binary = "";
  for (const byte of bytes) {
    binary += String.fromCharCode(byte);
  }
  return btoa(binary).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}

/**
 * Read the key out of a share URL.
 *
 * Returns `null` when there is no fragment: the caller shows "this link is
 * missing its key" rather than a passcode field that could never work.
 */
export function keyFromUrl(url: string | URL): string | null {
  let fragment: string;
  try {
    fragment = url instanceof URL ? url.hash : new URL(url, "https://manovia.app").hash;
  } catch {
    return null;
  }
  const raw = fragment.replace(/^#/, "");
  if (raw === "") {
    return null;
  }
  for (const pair of raw.split("&")) {
    const [name, value] = pair.split("=");
    if (name === KEY_FRAGMENT_PARAM && value !== undefined && value !== "") {
      return value;
    }
  }
  return null;
}

/**
 * Derive the AES-GCM content key for one share.
 *
 * The derived key is non-extractable: the page can use it and cannot read it
 * back, so a compromised script can open this document but cannot exfiltrate a
 * key that would open it again later.
 */
export async function deriveShareKey(options: {
  secret: string;
  passcode: string;
  token: string;
}): Promise<CryptoKey> {
  const { secret, passcode, token } = options;
  const bits = await deriveShareKeyBits({ secret, passcode, token });
  try {
    return await subtle().importKey("raw", bits as BufferSource, { name: "AES-GCM" }, false, [
      "decrypt",
    ]);
  } catch (error) {
    throw new ShareCryptoUnavailable("could not import the derived key", { cause: error });
  }
}

/**
 * The raw 32 derived bytes, before they become a `CryptoKey`.
 *
 * Exported separately so a test can compare them byte for byte against
 * `app/services/sharing/crypto.derive_key` — the one check that proves the two
 * implementations of the derivation agree. Nothing in the app calls it.
 */
export async function deriveShareKeyBits(options: {
  secret: string;
  passcode: string;
  token: string;
}): Promise<Uint8Array> {
  const { secret, passcode, token } = options;
  if (passcode.trim() === "") {
    throw new ShareCryptoUnavailable("a passcode is required to derive the content key");
  }
  if (token.trim() === "") {
    throw new ShareCryptoUnavailable("a share token is required to derive the content key");
  }
  let secretBytes: Uint8Array;
  try {
    secretBytes = fromBase64Url(secret);
  } catch {
    throw new ShareDecryptFailed("malformed");
  }
  if (secretBytes.byteLength !== SECRET_BYTES) {
    throw new ShareDecryptFailed("malformed");
  }

  const encoder = new TextEncoder();
  const passcodeBytes = encoder.encode(passcode);
  const material = new Uint8Array(secretBytes.byteLength + 1 + passcodeBytes.byteLength);
  material.set(secretBytes, 0);
  material[secretBytes.byteLength] = 0x00;
  material.set(passcodeBytes, secretBytes.byteLength + 1);

  try {
    const salt = new Uint8Array(
      await subtle().digest("SHA-256", encoder.encode(token) as BufferSource),
    );
    const baseKey = await subtle().importKey("raw", material as BufferSource, "HKDF", false, [
      "deriveBits",
    ]);
    const bits = await subtle().deriveBits(
      {
        name: "HKDF",
        hash: "SHA-256",
        salt: salt as BufferSource,
        info: encoder.encode(HKDF_INFO) as BufferSource,
      },
      baseKey,
      KEY_LENGTH_BITS,
    );
    return new Uint8Array(bits);
  } catch (error) {
    if (error instanceof ShareCryptoUnavailable || error instanceof ShareDecryptFailed) {
      throw error;
    }
    throw new ShareCryptoUnavailable("could not derive a key for this share", { cause: error });
  }
}

/** Decrypt one document to bytes. */
export async function decryptDocument(
  key: CryptoKey,
  document: { ciphertext: string; nonce: string; aad: string; algorithm: string },
): Promise<Uint8Array> {
  if (document.algorithm !== ALGORITHM) {
    // A document encrypted with something else is not one this page can read,
    // and guessing would be worse than refusing.
    throw new ShareDecryptFailed("malformed");
  }
  let ciphertext: Uint8Array;
  let nonce: Uint8Array;
  try {
    ciphertext = fromBase64Url(document.ciphertext);
    nonce = fromBase64Url(document.nonce);
  } catch {
    throw new ShareDecryptFailed("malformed");
  }
  if (nonce.byteLength !== NONCE_BYTES || ciphertext.byteLength < TAG_BYTES) {
    throw new ShareDecryptFailed("malformed");
  }
  try {
    const plaintext = await subtle().decrypt(
      {
        name: "AES-GCM",
        iv: nonce as BufferSource,
        additionalData: new TextEncoder().encode(document.aad) as BufferSource,
        tagLength: 128,
      },
      key,
      ciphertext as BufferSource,
    );
    return new Uint8Array(plaintext);
  } catch {
    // GCM reports every failure identically, and so does this function.
    throw new ShareDecryptFailed("decrypt-failed");
  }
}

/** Decrypt one document to text (the payload and the FHIR bundle are JSON). */
export async function decryptText(
  key: CryptoKey,
  document: { ciphertext: string; nonce: string; aad: string; algorithm: string },
): Promise<string> {
  return new TextDecoder().decode(await decryptDocument(key, document));
}
