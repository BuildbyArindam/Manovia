/**
 * Onboarding copy.
 *
 * Tone rules (AGENTS.md): warm, plain, short, non-judgemental, no toxic
 * positivity. Nothing here promises an outcome, and nothing claims Manovia is a
 * person or a clinician.
 *
 * The AI-disclosure text and the consent versions are *fallbacks*: the server is
 * the source of truth (`GET /api/v1/consent/requirements`), and
 * `src/onboarding/content.test.ts` fails if these copies drift from
 * `backend/app/content/consent_documents.json`.
 *
 * Day 23: every string shown in the flow now comes from the locale tree through
 * small functions below, so the words re-evaluate when the language changes.
 * `FALLBACK_AI_DISCLOSURE` stays a plain English constant: it is the offline
 * fallback and the value the drift test pins against the backend document.
 */

import type { ConsentKind } from "@/lib/endpoints";
import { t } from "@/lib/i18n/i18n";

export const FALLBACK_CONSENT_VERSION = "2026-10-01";

/** English fallback — source of truth for the drift test; UI renders via `aiDisclosureText()`. */
export const FALLBACK_AI_DISCLOSURE =
  "Manovia is an AI-powered self-help companion. The replies you get are generated by an AI, " +
  "not written by a human therapist or counsellor. It cannot diagnose you, cannot give medical " +
  "or medication advice, and is not an emergency or crisis service — if you are in danger or " +
  "thinking about harming yourself, please contact your local emergency services or a helpline " +
  "right away. Sharing how you feel can still help you reflect and feel less alone. You are in " +
  "control: you choose what to write, you can stop at any time, and you can delete your account " +
  "and its data whenever you want.";

/** Localised disclosure used by the UI; identical to the fallback in English. */
export function aiDisclosureText(): string {
  return t("onboarding.aiDisclosure");
}

