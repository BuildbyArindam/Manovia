import { fileURLToPath } from "node:url";

import react from "@vitejs/plugin-react";
import { VitePWA } from "vite-plugin-pwa";
import type { ManifestTransform } from "workbox-build";
import { defineConfig } from "vitest/config";

/**
 * Single Vite/Vitest configuration.
 *
 * The dev server proxies `/api` to the FastAPI backend so the browser only ever
 * talks to its own origin (the sandbox preview is served through a proxy host,
 * so nothing may call `localhost` from the client).
 */
/**
 * Content-Security-Policy for the *dev* server.
 *
 * `script-src` needs `'unsafe-inline'` here and only here: `@vitejs/plugin-react`
 * injects an inline Refresh preamble into the page, and `'unsafe-eval'` is what
 * the HMR client needs for source-map evaluation. Production is served by
 * `docker/nginx.conf`, which ships the strict policy (`script-src 'self'`) and
 * is asserted by `src/security/csp.test.ts` — so this dev relaxation can never
 * be what protects a real deployment.
 *
 * `connect-src` allows the HMR websocket (`ws:`) and nothing else off-origin;
 * everything else is same-origin, which is what makes the proxy-only topology
 * (the browser never calls `localhost` directly) enforceable rather than merely
 * conventional.
 *
 * The two Google Fonts origins mirror the production allowance (see
 * `docker/security-headers.conf`) so Hindi and Bengali render with Noto Sans
 * Devanagari / Bengali in development too.
 */
export const DEV_CSP = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline' 'unsafe-eval'",
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
  "img-src 'self' data:",
  "font-src 'self' https://fonts.gstatic.com",
  "connect-src 'self' ws: wss:",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join("; ");

/**
 * Day 25 — chunks that are not worth a byte of somebody's data plan offline.
 *
 * The service worker precaches the app shell so the app opens with no network.
 * Insights is the one surface that is useless offline (it is a view of
 * server-side data) and it carries the chart library, which is the single
 * largest chunk in the build — so it is left out of the precache and fetched
 * the first time somebody opens it online, exactly as before.
 */
const PRECACHE_EXCLUDED_CHUNKS = [/^assets\/charts-/, /^assets\/InsightsPage-/];

export const filterPrecacheManifest: ManifestTransform = (entries) => ({
  manifest: entries.filter(
    (entry) => !PRECACHE_EXCLUDED_CHUNKS.some((pattern) => pattern.test(entry.url)),
  ),
  warnings: [],
});

/** Vendor code that should not be re-downloaded when only app code changes. */
function manualChunks(id: string): string | undefined {
  if (!id.includes("node_modules")) {
    return undefined;
  }
  // The chart stack (recharts + d3 + its helpers) only ever loads with Insights.
  if (
    /node_modules\/(recharts|d3-|victory-vendor|decimal\.js|es-toolkit|immer|redux|@reduxjs|reselect|react-redux|use-sync-external-store|eventemitter3|tiny-invariant|clsx)/.test(
      id,
    )
  ) {
    return "charts";
  }
  if (
    /node_modules\/(react|react-dom|scheduler|react-router|react-router-dom|@remix-run)\//.test(id)
  ) {
    return "react";
  }
  if (/node_modules\/(i18next|react-i18next|@tanstack)\//.test(id)) {
    return "framework";
  }
  return undefined;
}

const isVitest = process.env.VITEST !== undefined;

export default defineConfig({
  plugins: [
    react(),
    // The PWA plugin only matters for `vite build`; the unit tests never load
    // it, so a test run cannot generate or depend on a service worker.
    ...(isVitest
      ? []
      : [
          VitePWA({
            strategies: "injectManifest",
            srcDir: "src/sw",
            filename: "sw.ts",
            // Registered by our own module (src/pwa/registerServiceWorker.ts):
            // an injected inline registration script is exactly what the strict
            // production CSP (`script-src 'self'`) refuses to run.
            injectRegister: false,
            registerType: "prompt",
            // The manifest is a static, reviewed file in public/ (with the
            // original icons generated by scripts/generate-icons.mjs).
            manifest: false,
            injectManifest: {
              globPatterns: ["**/*.{js,css,html,svg,png,webmanifest}"],
              manifestTransforms: [filterPrecacheManifest],
              // A precache entry larger than this is a mistake, not an asset.
              maximumFileSizeToCacheInBytes: 600 * 1024,
            },
            devOptions: { enabled: false },
          }),
        ]),
  ],
  resolve: {
    alias: {
      "@": fileURLToPath(new URL("./src", import.meta.url)),
    },
  },
  server: {
    // Bind on every interface: the preview proxy reaches the dev server by host
    // name, never by 127.0.0.1.
    host: true,
    port: 5173,
    allowedHosts: true,
    headers: {
      "Content-Security-Policy": DEV_CSP,
      "X-Content-Type-Options": "nosniff",
      "Referrer-Policy": "no-referrer",
    },
    proxy: {
      "/api": {
        target: process.env.VITE_API_PROXY_TARGET ?? "http://127.0.0.1:8000",
        // Day 25: keep the browser's Host header, exactly as docker/nginx.conf
        // does (`proxy_set_header Host $host`). The API's OriginGuard (Day 22)
        // accepts an unsafe request when Origin matches Host; rewriting Host to
        // the backend's address made every write through this proxy look
        // cross-origin unless that origin was added to ALLOWED_ORIGINS by hand.
        changeOrigin: false,
      },
    },
  },
  preview: {
    host: true,
    port: 4173,
    allowedHosts: true,
    headers: {
      "Content-Security-Policy": DEV_CSP,
      "X-Content-Type-Options": "nosniff",
      "Referrer-Policy": "no-referrer",
    },
    // Day 25: `vite preview` serves the production build (service worker
    // included), so it needs the same same-origin /api proxy as the dev server
    // — the browser must never call the backend directly.
    proxy: {
      "/api": {
        target: process.env.VITE_API_PROXY_TARGET ?? "http://127.0.0.1:8000",
        // Same-origin semantics as nginx: see the dev proxy above.
        changeOrigin: false,
      },
    },
  },
  build: {
    // The manifest lets scripts/check-bundle-budget.mjs follow each route's
    // real import graph instead of guessing from file names.
    manifest: true,
    rollupOptions: {
      output: { manualChunks },
    },
  },
  test: {
    // The PWA plugin is not loaded under Vitest, so its virtual module is not
    // either; the registration code only imports it in production builds.
    alias: {
      "virtual:pwa-register": fileURLToPath(
        new URL("./src/test/pwaRegisterStub.ts", import.meta.url),
      ),
    },
    environment: "jsdom",
    globals: true,
    setupFiles: ["./vitest.setup.ts"],
    include: ["src/**/*.test.{ts,tsx}"],
    restoreMocks: true,
  },
});
