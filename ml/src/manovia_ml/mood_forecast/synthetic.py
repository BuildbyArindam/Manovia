"""Seeded state-space simulator for synthetic, non-personal mood histories.

Assumptions are intentionally small and inspectable:

* each synthetic user has a baseline, slow linear drift, weekly sine wave,
  factor-effect coefficients, an AR(1) residual and an individual logging rate;
* sleep, exercise, social contact and workload affect latent valence, while
  additional closed factor tags provide context features;
* daily logging depends on the user's rate and weekday only, **not** on the
  latent mood, so missingness is not made artificially easy by hiding low days;
* observed valence and energy are rounded to the product's 1--5 check-in scale;
* the generator creates no text and accepts no real-user input.

This is a controlled simulator, not a claim that real people follow these
coefficients. The panel can be regenerated byte-for-byte from its config and
seed. Data bytes are transient/DVC-managed and are never committed to Git.
"""

from __future__ import annotations

import hashlib
import json
from collections.abc import Iterable
from dataclasses import dataclass
from datetime import date, timedelta
from typing import Final

import numpy as np

GENERATOR_VERSION: Final = "state-space-v1"
FACTOR_TAGS: Final[tuple[str, ...]] = (
    "study",
    "work",
    "family",
    "friends",
    "health",
    "money",
    "weather",
)


@dataclass(frozen=True)
class UserMoodParameters:
    """One user's synthetic latent-state and logging parameters."""

    user_id: str
    baseline: float
    energy_baseline: float
    trend_per_day: float
    weekly_amplitude: float
    weekly_phase: float
    ar1: float
    innovation_sd: float
    logging_probability: float
    sleep_effect: float
    exercise_effect: float
    social_effect: float
    workload_effect: float


@dataclass(frozen=True)
class MoodDay:
    """One calendar day; missing check-ins are explicit, not filled as labels."""

    user_id: str
    day_index: int
    day: date
    observed: bool
    valence: int | None
    energy: int | None
    sleep_tag: bool | None
    exercise_done: bool | None
    factors: tuple[str, ...]


@dataclass(frozen=True)
class MoodSeries:
    """A contiguous daily panel for one synthetic user."""

    user_id: str
    parameters: UserMoodParameters
    days: tuple[MoodDay, ...]


@dataclass(frozen=True)
class MoodPanel:
    """The complete, deterministic synthetic cohort."""

    seed: int
    start_date: date
    generator_version: str
    users: tuple[MoodSeries, ...]

    @property
    def daily_rows(self) -> int:
        """Number of calendar rows, including explicit unlogged days."""
        return sum(len(user.days) for user in self.users)

    @property
    def logged_days(self) -> int:
        """Number of observed check-in days in the panel."""
        return sum(day.observed for user in self.users for day in user.days)


def _user_parameters(
    user_id: str, rng: np.random.Generator, logging_probability: float
) -> UserMoodParameters:
    """Draw bounded individual parameters from the documentable simulator prior."""
    return UserMoodParameters(
        user_id=user_id,
        baseline=float(rng.uniform(2.25, 3.8)),
        energy_baseline=float(rng.uniform(2.5, 3.8)),
        trend_per_day=float(rng.uniform(-0.007, 0.007)),
        weekly_amplitude=float(rng.uniform(0.12, 0.42)),
        weekly_phase=float(rng.uniform(0.0, 2.0 * np.pi)),
        ar1=float(rng.uniform(0.45, 0.78)),
        innovation_sd=float(rng.uniform(0.24, 0.46)),
        logging_probability=float(np.clip(logging_probability + rng.normal(0.0, 0.06), 0.5, 1.0)),
        sleep_effect=float(rng.uniform(-0.75, -0.25)),
        exercise_effect=float(rng.uniform(0.05, 0.38)),
        social_effect=float(rng.uniform(0.12, 0.5)),
        workload_effect=float(rng.uniform(-0.65, -0.18)),
    )


def _factor_context(rng: np.random.Generator) -> tuple[bool, bool, bool, bool, tuple[str, ...]]:
    """Generate factor presence; tags are exposed only on logged days."""
    sleep_tag = bool(rng.random() < 0.28)
    exercise_done = bool(rng.random() < 0.30)
    social_contact = bool(rng.random() < 0.36)
    workload = bool(rng.random() < 0.42)
    factors: list[str] = []
    if social_contact:
        factors.append("friends")
    if workload:
        factors.append("work")
    for tag, probability in (
        ("study", 0.18),
        ("family", 0.20),
        ("health", 0.12),
        ("money", 0.10),
        ("weather", 0.25),
    ):
        if rng.random() < probability:
            factors.append(tag)
    return sleep_tag, exercise_done, social_contact, workload, tuple(factors)


def generate_synthetic_panel(
    *,
    seed: int,
    users: int,
    days: int,
    start_date: date | str = date(2025, 1, 6),
    logging_probability: float = 0.82,
) -> MoodPanel:
    """Simulate user-specific weekly/trend/factor/AR(1) mood states.

    The stream is split per user with ``SeedSequence.spawn``. Adding a user does
    not change the already-generated users, and the same parameters + seed
    produce identical panel objects.
    """
    if not 0 <= seed < 2**32:
        raise ValueError("seed must fit in 4 bytes")
    if users < 3:
        raise ValueError("at least three users are needed for train/calibration/test groups")
    if days < 35:
        raise ValueError("days must be at least 35 to supply a 28-day input and 3-day target")
    if not 0.0 < logging_probability <= 1.0:
        raise ValueError("logging_probability must be in (0, 1]")
    start = date.fromisoformat(start_date) if isinstance(start_date, str) else start_date

    user_seeds = np.random.SeedSequence(seed).spawn(users)
    series: list[MoodSeries] = []
    for user_number, user_seed in enumerate(user_seeds):
        rng = np.random.default_rng(user_seed)
        user_id = f"synthetic-{user_number:04d}"
        parameters = _user_parameters(user_id, rng, logging_probability)
        state_noise = float(rng.normal(0.0, parameters.innovation_sd))
        energy_noise = float(rng.normal(0.0, parameters.innovation_sd * 1.15))
        records: list[MoodDay] = []

        for day_index in range(days):
            sleep_tag, exercise_done, social_contact, workload, factor_tags = _factor_context(rng)
            weekday = (start + timedelta(days=day_index)).weekday()
            # Logging may be less frequent on weekends. It never depends on
            # valence, energy or the latent innovation (missing-at-random given
            # weekday and the user's rate).
            weekend_multiplier = 0.90 if weekday >= 5 else 1.0
            log_probability = min(1.0, parameters.logging_probability * weekend_multiplier)
            observed = bool(rng.random() < log_probability)

            weekly = parameters.weekly_amplitude * np.sin(
                (2.0 * np.pi * day_index / 7.0) + parameters.weekly_phase
            )
            state_noise = parameters.ar1 * state_noise + float(
                rng.normal(0.0, parameters.innovation_sd)
            )
            factor_value = (
                parameters.sleep_effect * sleep_tag
                + parameters.exercise_effect * exercise_done
                + parameters.social_effect * social_contact
                + parameters.workload_effect * workload
            )
            latent_valence = (
                parameters.baseline
                + parameters.trend_per_day * day_index
                + weekly
                + factor_value
                + state_noise
            )
            energy_noise = 0.62 * energy_noise + float(
                rng.normal(0.0, parameters.innovation_sd * 1.1)
            )
            latent_energy = (
                parameters.energy_baseline
                + 0.25 * (latent_valence - parameters.baseline)
                + 0.45 * parameters.sleep_effect * sleep_tag
                + 0.35 * parameters.exercise_effect * exercise_done
                + energy_noise
            )
            records.append(
                MoodDay(
                    user_id=user_id,
                    day_index=day_index,
                    day=start + timedelta(days=day_index),
                    observed=observed,
                    valence=int(np.clip(np.rint(latent_valence), 1, 5)) if observed else None,
                    energy=int(np.clip(np.rint(latent_energy), 1, 5)) if observed else None,
                    sleep_tag=sleep_tag if observed else None,
                    exercise_done=exercise_done if observed else None,
                    factors=tuple(sorted(factor_tags)) if observed else (),
                )
            )
        series.append(MoodSeries(user_id=user_id, parameters=parameters, days=tuple(records)))

    return MoodPanel(
        seed=seed,
        start_date=start,
        generator_version=GENERATOR_VERSION,
        users=tuple(series),
    )


def iter_jsonl(panel: MoodPanel) -> Iterable[str]:
    """Yield canonical dataset rows for DVC and a reproducible content hash."""
    for user in panel.users:
        for day in user.days:
            payload = {
                "user_id": day.user_id,
                "day_index": day.day_index,
                "day": day.day.isoformat(),
                "observed": day.observed,
                "valence": day.valence,
                "energy": day.energy,
                "sleep_tag": day.sleep_tag,
                "exercise_done": day.exercise_done,
                "factors": list(day.factors),
            }
            yield json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=True)


def dataset_sha256(panel: MoodPanel) -> str:
    """Hash canonical generated rows without writing or committing the panel."""
    digest = hashlib.sha256()
    for row in iter_jsonl(panel):
        digest.update(row.encode("utf-8"))
        digest.update(b"\n")
    return digest.hexdigest()


def panel_manifest(panel: MoodPanel) -> dict[str, object]:
    """Safe dataset metadata for DVC/MLflow; never includes latent trajectories."""
    return {
        "generator_version": panel.generator_version,
        "seed": panel.seed,
        "users": len(panel.users),
        "calendar_days_per_user": len(panel.users[0].days) if panel.users else 0,
        "daily_rows": panel.daily_rows,
        "logged_days": panel.logged_days,
        "sha256": dataset_sha256(panel),
        "start_date": panel.start_date.isoformat(),
        "factors": list(FACTOR_TAGS),
        "assumptions": [
            "weekly sine seasonality with period 7 days and user-specific phase/amplitude",
            "user-specific slow linear trend and bounded factor effects",
            "AR(1) residual with a per-user coefficient in [0.45, 0.78]",
            "logging missing-at-random given user rate and weekday, not latent mood",
            "observed valence and energy rounded and clipped to the 1-5 self-report scale",
        ],
    }


