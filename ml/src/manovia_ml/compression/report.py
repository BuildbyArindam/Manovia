"""The accuracy/recall-vs-size/latency tradeoff table (Day 34 deliverable 1).

One markdown table, three model rows (teacher, fp32 student, INT8 student)
per task, generated from measured JSON — never hand-typed numbers. The
smoke run's table is labelled plumbing wherever it is quoted, because its
teacher is a sklearn stand-in and its student is a hashed-feature linear
model (see ``distill.py``).
"""

from __future__ import annotations

import json
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

__all__ = ["comparison_table", "write_report"]


def _fmt(value: Any) -> str:
    if value is None:
        return "—"
    if isinstance(value, float):
        return f"{value:.4f}".rstrip("0").rstrip(".") if value < 100 else f"{value:.1f}"
    return str(value)


def comparison_table(rows: Sequence[Mapping[str, Any]]) -> str:
    """Markdown table from row dicts (see ``write_report`` for the schema)."""

    header = (
        "| model | size (MB) | p50 (ms) | p95 (ms) | safety crisis recall | "
        "emotion macro-F1 | accuracy |\n"
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |"
    )
    lines = [header]
    for row in rows:
        lines.append(
            "| {name} | {size} | {p50} | {p95} | {recall} | {f1} | {acc} |".format(
                name=row.get("name", "?"),
                size=_fmt(row.get("size_mb")),
                p50=_fmt(row.get("p50_latency_ms")),
                p95=_fmt(row.get("p95_latency_ms")),
                recall=_fmt(row.get("safety_crisis_recall")),
                f1=_fmt(row.get("emotion_macro_f1")),
                acc=_fmt(row.get("accuracy")),
            )
        )
    return "\n".join(lines) + "\n"


def write_report(
    *,
    title: str,
    rows: Sequence[Mapping[str, Any]],
    gates: Mapping[str, Any] | None,
    notes: Sequence[str],
    out_path: Path,
) -> Path:
    """Write the committed report: table + gate verdict + honesty notes."""

    lines = [
        f"# {title}",
        "",
        "Generated by `manovia_ml.compression.report` from measured JSON. "
        "Numbers without a run/artefact behind them are not quoted here.",
        "",
        comparison_table(rows),
    ]
    if gates is not None:
        verdict = "PASS" if gates.get("passed") else "FAIL"
        lines += ["", f"Release gates: **{verdict}**", ""]
        for check in gates.get("checks", []):
            mark = "PASS" if check.get("passed") else "FAIL"
            lines.append(f"- [{mark}] `{check.get('name')}` — {check.get('detail')}")
        lines.append("")
    if notes:
        lines += ["## Notes", ""]
        lines += [f"- {note}" for note in notes]
        lines.append("")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    return out_path


def rows_from_json(path: Path) -> list[dict[str, Any]]:
    payload = json.loads(Path(path).read_text(encoding="utf-8"))
    rows = payload.get("rows")
    if not isinstance(rows, list):
        raise ValueError(f"{path}: expected a {{'rows': [...]}} document")
    return [dict(row) for row in rows]
