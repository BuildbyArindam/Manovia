#: The windows a person can choose from. Short windows keep a share focused; the
#: longest one is a quarter, because a summary of a year is not a summary.
WINDOW_CHOICES: tuple[int, ...] = (14, 30, 90)
DEFAULT_WINDOW_DAYS = 30

#: Free-text budgets. Generous enough to be useful, small enough that a share
#: cannot become a second journal.
MAX_NOTE_CHARS = 2000
MAX_QUESTIONS = 10
MAX_QUESTION_CHARS = 300
MAX_THOUGHT_RECORDS = 10

#: How much history the assessments item summarises (most recent first).
MAX_ASSESSMENTS = 20

#: Mood rows read for the trend. The window bounds the query; this bounds the
#: memory of a person who checks in several times a day for a year.
MAX_MOOD_ROWS = 500

#: Exercise completions read for the helpfulness summary, before the window
#: filter. Same reasoning: a bound on memory, not on the person's history.
MAX_EXERCISE_ROWS = 500

#: Half-window comparison needs at least this many check-ins on each side before
#: the payload is allowed to use a direction word at all.
MIN_ENTRIES_FOR_DIRECTION = 3

#: Smallest mean difference worth calling a direction (on a 1-5 scale).
DIRECTION_EPSILON = 0.25

#: The banner text every export carries, in the payload, the PDF and the viewer.
DISCLAIMER_TITLE = "Patient-generated, not a diagnosis"
DISCLAIMER = (
    "This summary was generated by Manovia, a self-help companion, from entries "
    "the person made about themselves. It is patient-generated information: it is "
    "not a diagnosis, not a clinical assessment, and not a medical record. "
    "Screening scores are self-report labels for reflection only. Manovia is not "
    "an electronic health record and is not connected to one. If this document "
    "mentions risk of harm, treat it as a reason to ask, not as a triage score."
)

#: What is never in a share, said out loud on the consent screen.
NEVER_INCLUDED: tuple[str, ...] = (
    "chat conversations with Manovia",
    "journal entries",
    "the notes attached to mood check-ins",
    "your password, email or account identifiers (unless you tick 'Identify me')",
    "anything you did not tick",
)

#: Direction words, closed set: the UI and the PDF render these, so they cannot
#: be free text.
Direction = Literal["higher", "lower", "steady", "not_enough_data"]

DIRECTION_NOTE: dict[Direction, str] = {
    "higher": "Mood ratings in the second half of this window were higher than in the first half.",
    "lower": "Mood ratings in the second half of this window were lower than in the first half.",
    "steady": "Mood ratings were much the same across both halves of this window.",
    "not_enough_data": (
        "Not enough check-ins in this window to describe a direction. "
        "A direction needs at least three check-ins in each half."
    ),
}


