class ShareContentError(ValueError):
    """A selection that cannot be built into a document."""


class Strict(BaseModel):
    """Strict, extra-forbidding model for everything that leaves this module."""

    model_config = ConfigDict(extra="forbid")


class LabelCount(Strict):
    """One tag and how often it was used."""

    label: str
    count: int = Field(ge=0)


class MoodTrendSummary(Strict):
    """The mood item: numbers about check-ins, never their contents."""

    window_days: int
    window_start: datetime
    entries: int = Field(ge=0)
    first_check_in: datetime | None = None
    last_check_in: datetime | None = None
    mean_valence: float | None = None
    mean_energy: float | None = None
    earlier_mean_valence: float | None = None
    recent_mean_valence: float | None = None
    direction: Direction
    direction_note: str
    scale: str = "1 (low) to 5 (high)"
    top_emotions: list[LabelCount] = Field(default_factory=list)
    top_factors: list[LabelCount] = Field(default_factory=list)
    notes_included: Literal[False] = False


class AssessmentShare(Strict):
    """One screening result: date, total, band — and the verified LOINC term."""

    instrument: AssessmentInstrument
    instrument_name: str
    completed_at: datetime
    total: int = Field(ge=0)
    band: str
    band_label: str
    band_is_a_diagnosis: Literal[False] = False
    loinc_code: str
    loinc_display: str
    loinc_source_url: str
    ucum_unit: str
    item_answers_included: Literal[False] = False


class ThoughtRecordShare(Strict):
    """One thought record the person ticked, decrypted for this share only."""

    id: uuid.UUID
    created_at: datetime
    emotion: str
    intensity_before: int = Field(ge=0, le=100)
    intensity_after: int = Field(ge=0, le=100)
    what_helped: list[str] = Field(default_factory=list)
    situation: str
    automatic_thought: str
    evidence_for: str
    evidence_against: str
    balanced_thought: str


class ExerciseHelpfulnessRow(Strict):
    """One exercise, averaged."""

    title: str
    times: int = Field(ge=1)
    mean_before: float | None = None
    mean_after: float | None = None
    mean_change: float | None = None


class ExerciseHelpfulness(Strict):
    """The exercise item: ratings only."""

    window_days: int
    window_start: datetime
    completions: int = Field(ge=0)
    rated_completions: int = Field(ge=0)
    exercises: list[ExerciseHelpfulnessRow] = Field(default_factory=list)
    most_helpful: str | None = None
    #: The app's own wording for these ratings ("1 is very low; 5 is very good"),
    #: so a professional reading the summary and the person reading the app see
    #: one scale. A positive ``mean_change`` is an improvement.
    rating_scale: str = "1 (very low) to 5 (very good), rated before and after"
    #: Stated wherever the numbers are shown: association, not causation.
    change_caveat: str = (
        "A rating that moved is an association, not proof that the exercise caused it."
    )


class SharePayload(Strict):
    """The document. Everything the preview, the PDF and the bundle are made of."""

    schema_version: Literal[1] = 1
    kind: Literal["manovia.appointment-summary"] = "manovia.appointment-summary"
    generated_at: datetime
    window_days: int
    items: list[ShareItem]
    disclaimer_title: str = DISCLAIMER_TITLE
    disclaimer: str = DISCLAIMER
    never_included: list[str] = Field(default_factory=lambda: list(NEVER_INCLUDED))
    identity: str | None = None
    mood_trend: MoodTrendSummary | None = None
    assessments: list[AssessmentShare] | None = None
    thought_records: list[ThoughtRecordShare] | None = None
    exercise_helpfulness: ExerciseHelpfulness | None = None
    note: str | None = None
    questions: list[str] | None = None
    counts: dict[str, int] = Field(default_factory=dict)
    app: str = "Manovia"
    app_version: str = "1.0.0"

    def as_dict(self) -> dict[str, Any]:
        """JSON-ready dict for API responses (see :meth:`as_json` for the bytes)."""

        return self.model_dump(mode="json")

    def as_json(self) -> bytes:
        """Canonical UTF-8 JSON: the model's own field order, ``None`` kept.

        Canonical because these bytes are what gets encrypted and hashed — a
        re-serialisation that reordered keys or dropped empty fields would
        change the fingerprint the owner confirmed. Pydantic emits fields in
        declaration order, so the output is stable across runs and machines.
        """

        return self.model_dump_json(exclude_none=False).encode("utf-8")


class ShareRequest(Strict):
    """What the builder sends: a selection, a window, and the typed items."""

    items: list[ShareItem] = Field(min_length=1)
    window_days: int = DEFAULT_WINDOW_DAYS
    note: str | None = None
    questions: list[str] = Field(default_factory=list)
    thought_record_ids: list[uuid.UUID] = Field(default_factory=list)

    @model_validator(mode="after")
    def selection_is_coherent(self) -> ShareRequest:
        """Reject anything that would widen the share beyond what was ticked."""

        if len(set(self.items)) != len(self.items):
            raise ValueError("items must not repeat")
        if self.window_days not in WINDOW_CHOICES:
            raise ValueError(f"window_days must be one of {WINDOW_CHOICES}")
        selected = set(self.items)

        note = (self.note or "").strip()
        if ShareItem.NOTE in selected:
            if not note:
                raise ValueError("Write a note, or untick 'A note for my appointment'.")
            if len(note) > MAX_NOTE_CHARS:
                raise ValueError(f"A note must be at most {MAX_NOTE_CHARS} characters.")
        elif note:
            raise ValueError("A note was sent but 'note' is not selected.")

        questions = [question.strip() for question in self.questions if question.strip()]
        if ShareItem.QUESTIONS in selected:
            if not questions:
                raise ValueError("Add a question, or untick 'Questions I want to ask'.")
            if len(questions) > MAX_QUESTIONS:
                raise ValueError(f"At most {MAX_QUESTIONS} questions.")
            if any(len(question) > MAX_QUESTION_CHARS for question in questions):
                raise ValueError(f"Each question must be at most {MAX_QUESTION_CHARS} characters.")
        elif questions:
            raise ValueError("Questions were sent but 'questions' is not selected.")

        if ShareItem.THOUGHT_RECORDS in selected:
            if not self.thought_record_ids:
                raise ValueError("Choose at least one thought record, or untick the item.")
            if len(set(self.thought_record_ids)) != len(self.thought_record_ids):
                raise ValueError("thought_record_ids must not repeat")
            if len(self.thought_record_ids) > MAX_THOUGHT_RECORDS:
                raise ValueError(f"At most {MAX_THOUGHT_RECORDS} thought records.")
        elif self.thought_record_ids:
            raise ValueError("Thought records were selected but the item is not ticked.")

        return self

    @property
    def selected(self) -> list[ShareItem]:
        """The ticked items in catalogue order."""

        chosen = set(self.items)
        return [member for member in SHARE_ITEM_ORDER if member in chosen]

    @property
    def cleaned_questions(self) -> list[str]:
        """Trimmed, non-empty questions in the order they were written."""

        return [question.strip() for question in self.questions if question.strip()]


def _mean(values: Sequence[float]) -> float | None:
    """The mean of ``values``, or ``None`` when there are none."""

    return round(sum(values) / len(values), 2) if values else None


def _window_start(now: datetime, window_days: int) -> datetime:
    """Inclusive start of the window, in UTC."""

    return now - timedelta(days=window_days)


async def _mood_trend(
    session: AsyncSession, user: User, *, request: ShareRequest, now: datetime
) -> MoodTrendSummary:
    """Numbers over the check-ins in the window. The notes are never loaded."""

    start = _window_start(now, request.window_days)
    rows = await MoodRepository(session).insights_rows(user.id, since=start)
    bounded = list(rows)[-MAX_MOOD_ROWS:]
    valence = [float(row.valence) for row in bounded]
    energy = [float(row.energy) for row in bounded]
    emotions = Counter(label for row in bounded for label in row.emotions)
    factors = Counter(name for row in bounded for name in row.factors)

    instants = sorted(as_utc(row.created_at) for row in bounded)
    midpoint = start + timedelta(days=request.window_days / 2)
    earlier = [float(row.valence) for row in bounded if as_utc(row.created_at) < midpoint]
    recent = [float(row.valence) for row in bounded if as_utc(row.created_at) >= midpoint]

    direction: Direction = "not_enough_data"
    earlier_mean = _mean(earlier)
    recent_mean = _mean(recent)
    if (
        len(earlier) >= MIN_ENTRIES_FOR_DIRECTION
        and len(recent) >= MIN_ENTRIES_FOR_DIRECTION
        and earlier_mean is not None
        and recent_mean is not None
    ):
        difference = recent_mean - earlier_mean
        if difference > DIRECTION_EPSILON:
            direction = "higher"
        elif difference < -DIRECTION_EPSILON:
            direction = "lower"
        else:
            direction = "steady"

    return MoodTrendSummary(
        window_days=request.window_days,
        window_start=start,
        entries=len(bounded),
        first_check_in=instants[0] if instants else None,
        last_check_in=instants[-1] if instants else None,
        mean_valence=_mean(valence),
        mean_energy=_mean(energy),
        earlier_mean_valence=earlier_mean,
        recent_mean_valence=recent_mean,
        direction=direction,
        direction_note=DIRECTION_NOTE[direction],
        top_emotions=[
            LabelCount(label=label, count=count) for label, count in emotions.most_common(5)
        ],
        top_factors=[
            LabelCount(label=label, count=count) for label, count in factors.most_common(5)
        ],
    )


async def _assessments(session: AsyncSession, user: User) -> list[AssessmentShare]:
    """Screening totals in the window, newest first, with their verified LOINC term."""

    # Assessments are deliberately not windowed: the item *is* the history, and a
    # person with three screeners in a year wants all three in front of them.
    instruments = get_instruments()
    shared: list[AssessmentShare] = []
    for instrument in (AssessmentInstrument.PHQ9, AssessmentInstrument.GAD7):
        rows = await AssessmentRepository(session).list_for_user(
            user.id, instrument=instrument, limit=MAX_ASSESSMENTS
        )
        definition = instruments[instrument]
        term = loinc_for(instrument)
        for row in rows:
            band = definition.band_for(row.total)
            shared.append(
                AssessmentShare(
                    instrument=instrument,
                    instrument_name=definition.short_name,
                    completed_at=as_utc(row.created_at),
                    total=row.total,
                    band=row.band.value,
                    band_label=band.label,
                    loinc_code=term.code,
                    loinc_display=term.display,
                    loinc_source_url=term.source_url,
                    ucum_unit=term.ucum_unit,
                )
            )
    shared.sort(key=lambda item: item.completed_at, reverse=True)
    return shared


async def _thought_records(
    session: AsyncSession, user: User, *, request: ShareRequest
) -> list[ThoughtRecordShare]:
    """The ticked records, decrypted here and nowhere else."""

    statement = (
        select(CBTRecord)
        .where(CBTRecord.user_id == user.id, CBTRecord.id.in_(request.thought_record_ids))
        .order_by(CBTRecord.created_at.desc(), CBTRecord.id.desc())
    )
    rows = list((await session.execute(statement)).scalars().all())
    if len(rows) != len(set(request.thought_record_ids)):
        found = {row.id for row in rows}
        missing = [str(item) for item in request.thought_record_ids if item not in found]
        raise ShareContentError(
            "Some thought records could not be found or are not yours: "
            + ", ".join(missing[:MAX_THOUGHT_RECORDS])
        )
    records: list[ThoughtRecordShare] = []
    for row in rows:
        try:
            text = {
                field: decrypt_field(
                    getattr(row, f"{field}_encrypted"),
                    user_id=row.user_id,
                    field_name=cbt_aad(field),
                    wrapped_dek=user.data_key_encrypted,
                )
                for field in CBT_TEXT_FIELDS
            }
        except (DecryptError, CipherNotConfiguredError) as exc:
            raise ShareContentError("A thought record could not be decrypted.") from exc
        records.append(
            ThoughtRecordShare(
                id=row.id,
                created_at=as_utc(row.created_at),
                emotion=row.emotion,
                intensity_before=row.intensity_before,
                intensity_after=row.intensity_after,
                what_helped=[str(tag) for tag in row.what_helped],
                **text,
            )
        )
    return records


async def _exercise_helpfulness(
    session: AsyncSession, user: User, *, request: ShareRequest, now: datetime
) -> ExerciseHelpfulness:
    """Ratings per exercise over the window."""

    start = _window_start(now, request.window_days)
    rows = [
        row
        for row in await ExerciseRepository(session).list_for_user(user.id, limit=MAX_EXERCISE_ROWS)
        if as_utc(row.created_at) >= start
    ]
    grouped: dict[str, list[tuple[int | None, int | None]]] = {}
    for row in rows:
        grouped.setdefault(row.exercise_title, []).append((row.pre_rating, row.post_rating))

    exercises: list[ExerciseHelpfulnessRow] = []
    for title, ratings in sorted(grouped.items(), key=lambda item: (-len(item[1]), item[0])):
        before = [float(pre) for pre, _ in ratings if pre is not None]
        after = [float(post) for _, post in ratings if post is not None]
        changes = [
            float(post) - float(pre)
            for pre, post in ratings
            if pre is not None and post is not None
        ]
        exercises.append(
            ExerciseHelpfulnessRow(
                title=title,
                times=len(ratings),
                mean_before=_mean(before),
                mean_after=_mean(after),
                mean_change=_mean(changes),
            )
        )
    # Only an actual improvement is a candidate. On this scale (1 very low,
    # 5 very good) a negative change means the person rated themselves worse
    # afterwards, and calling that "what helped most" would be a false claim in a
    # document a professional may act on. With no improvement anywhere, the
    # summary says nothing rather than picking the least bad.
    best = max(
        (row for row in exercises if row.mean_change is not None and row.mean_change > 0),
        key=lambda row: float(row.mean_change or 0.0),
        default=None,
    )
    return ExerciseHelpfulness(
        window_days=request.window_days,
        window_start=start,
        completions=len(rows),
        rated_completions=sum(
            1 for row in rows if row.pre_rating is not None and row.post_rating is not None
        ),
        exercises=exercises[:10],
        most_helpful=best.title if best is not None else None,
    )


async def build_payload(
    session: AsyncSession,
    user: User,
    request: ShareRequest,
    *,
    now: datetime | None = None,
) -> SharePayload:
    """Assemble the one document this selection means.

    Raises :class:`ShareContentError` when a selected row cannot be read (a
    thought record that is not theirs, or one whose ciphertext will not decrypt):
    a share that silently drops an item the person ticked is a share that lies
    about its own contents.
    """

    moment = now or utcnow()
    selected = request.selected
    payload = SharePayload(generated_at=moment, window_days=request.window_days, items=selected)
    counts: dict[str, int] = {}

    if ShareItem.IDENTITY in selected:
        payload.identity = user.email or "Anonymous account (no email on file)"
        counts["identity"] = 1 if user.email else 0

    if ShareItem.MOOD_TREND in selected:
        payload.mood_trend = await _mood_trend(session, user, request=request, now=moment)
        counts["mood_check_ins"] = payload.mood_trend.entries

    if ShareItem.ASSESSMENTS in selected:
        payload.assessments = await _assessments(session, user)
        counts["assessments"] = len(payload.assessments)

    if ShareItem.THOUGHT_RECORDS in selected:
        payload.thought_records = await _thought_records(session, user, request=request)
        counts["thought_records"] = len(payload.thought_records)

    if ShareItem.EXERCISE_HELPFULNESS in selected:
        payload.exercise_helpfulness = await _exercise_helpfulness(
            session, user, request=request, now=moment
        )
        counts["exercise_completions"] = payload.exercise_helpfulness.completions

    if ShareItem.NOTE in selected:
        payload.note = (request.note or "").strip()
        counts["note_chars"] = len(payload.note)

    if ShareItem.QUESTIONS in selected:
        payload.questions = request.cleaned_questions
        counts["questions"] = len(payload.questions)

    payload.counts = counts
    return payload


def consent_lines(payload: SharePayload) -> list[str]:
    """The bullet list the confirmation screen shows, and the owner hashes.

    Rendered from the payload itself, so the sentence a person confirms cannot
    drift from the document that was built: one input, two outputs.
    """

    lines: list[str] = []
    if payload.identity:
        lines.append(f"Identifies you as: {payload.identity}")
    if payload.mood_trend is not None:
        trend = payload.mood_trend
        lines.append(
            f"Mood summary: {trend.entries} check-ins over {trend.window_days} days "
            f"(average mood {trend.mean_valence if trend.mean_valence is not None else 'n/a'}, "
            f"average energy {trend.mean_energy if trend.mean_energy is not None else 'n/a'})."
        )
    if payload.assessments is not None:
        instruments = (
            ", ".join(sorted({item.instrument_name for item in payload.assessments})) or "none"
        )
        lines.append(
            f"Screening history: {len(payload.assessments)} results ({instruments}). "
            "Totals and band labels only — your individual answers are not included."
        )
    if payload.thought_records is not None:
        lines.append(
            f"Thought records: {len(payload.thought_records)} you chose, with everything you wrote "
            "in them."
        )
    if payload.exercise_helpfulness is not None:
        lines.append(
            f"Exercise helpfulness: {payload.exercise_helpfulness.completions} completions "
            f"across {len(payload.exercise_helpfulness.exercises)} exercises."
        )
    if payload.note is not None:
        lines.append(f"Your note: {len(payload.note)} characters.")
    if payload.questions is not None:
        lines.append(f"Your questions: {len(payload.questions)}.")
    if not lines:
        lines.append("Nothing is selected, so nothing would be shared.")
    lines.append("Never included: " + "; ".join(payload.never_included) + ".")
    lines.append(payload.disclaimer)
    return lines


