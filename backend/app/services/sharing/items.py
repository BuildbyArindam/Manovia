"""What a share contains: the item catalogue, and the exact document it becomes.

Two jobs, deliberately in one module. The **catalogue** is the closed list a
person can choose from, with a sentence each for what an item *includes* and what
it never includes — that sentence is the comprehension half of the consent screen,
so it lives next to the code that decides what is actually collected. The
**builder** turns a selection into one :class:`SharePayload`, which is the single
object the preview shows, the PDF renders, the FHIR bundle is made from, and the
ciphertext contains. One source of truth: what you preview is what you send.

Privacy rules this module enforces rather than hopes for:

* **Nothing arrives that was not selected.** A request carrying a note without
  the ``note`` item is rejected, not silently dropped: a client bug must not be
  able to widen a share.
* **Free text is never collected implicitly.** Mood check-in notes and journal
  entries are not reachable from here at all — the queries used project only the
  columns an item needs (:meth:`MoodRepository.insights_rows` never loads the
  encrypted note).
* **Assessment answers stay per-item private.** Totals, bands and dates are
  shared; the individual answers are not, which is also what keeps the FHIR
  bundle's QuestionnaireResponses small enough to read.
* **Counts, not just content.** The payload carries how many rows each item
  summarised, so the preview can say "12 check-ins" and the reader can see a
  summary built on one data point is thin.
"""

