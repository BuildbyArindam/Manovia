"""Mood check-ins: the vocabulary, the streak arithmetic, and the insights.

Three things live here, all deliberately free of HTTP and of the database:

* :mod:`app.services.mood.taxonomy` — the closed vocabularies (nine emotion
  labels, eight context factors) and the caps that keep a check-in short.
* :mod:`app.services.mood.streak` — the forgiving streak rules, computed in the
  person's own timezone from raw timestamps.
* :mod:`app.services.mood.insights` — what a history of check-ins can honestly
  be said to show: rolling averages, a trend with a minimum-data rule, tag
  associations with resampled intervals, and time-of-day and weekday patterns.
  Pure functions over numbers, with localised sentences filled into reviewed
  templates (``app.content.insights``) and never assembled from f-strings.

The endpoints that tie them to the database are ``app.api.v1.mood`` and
``app.api.v1.insights``.
"""

