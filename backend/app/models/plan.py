"""``plan_items`` — one persisted daily-plan suggestion.

The planner (:mod:`app.services.plan.daily_plan`) is a pure, table-driven rule
set; this table is only what it produced for a person on a local day, plus what
the person did with each suggestion. Everything here is metadata: a kind, an
optional content reference (an exercise id), reviewed copy, and a status. There
is no free text, so nothing in this table is encrypted — the same reasoning the
assessment results use.

Uniqueness: one row per person, per local day, per kind. The local day is the
calendar day in the timezone the request supplied, exactly the way the mood
streak decides what "today" is, so a second ``GET /plan/today`` on the same day
returns the same rows with their statuses intact instead of re-rolling the plan.
"""

from __future__ import annotations

import uuid
from datetime import date
from typing import TYPE_CHECKING

import sqlalchemy as sa
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base, CreatedAtMixin, enum_check, enum_type
from app.models.enums import PlanItemKind, PlanItemStatus

if TYPE_CHECKING:
    from app.models.user import User


class PlanItem(Base, CreatedAtMixin):
    """One suggestion for one person on one local day."""

    __tablename__ = "plan_items"

    id: Mapped[uuid.UUID] = mapped_column(sa.Uuid(), primary_key=True, default=uuid.uuid4)
    user_id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid(),
        sa.ForeignKey("users.id", name="fk_plan_items_user_id_users", ondelete="CASCADE"),
        nullable=False,
    )
    #: The calendar day (in the requester's timezone) this suggestion belongs to.
    plan_date: Mapped[date] = mapped_column(sa.Date(), nullable=False)
    kind: Mapped[PlanItemKind] = mapped_column(enum_type(PlanItemKind), nullable=False)
    #: Optional content reference, e.g. an exercise id. Nullable: check-in,
    #: rest and support suggestions point at a surface, not a content item.
    ref: Mapped[str | None] = mapped_column(sa.String(64))
    #: Reviewed copy, never generated by a model.
    title: Mapped[str] = mapped_column(sa.String(300), nullable=False)
    #: The "why this?" explanation. Always present — a suggestion without a
    #: reason is a nag.
    why: Mapped[str] = mapped_column(sa.String(1000), nullable=False)
    status: Mapped[PlanItemStatus] = mapped_column(
        enum_type(PlanItemStatus), nullable=False, default=PlanItemStatus.PENDING
    )

    user: Mapped[User] = relationship(back_populates="plan_items")

    __table_args__ = (
        sa.Index("ix_plan_items_user_id_plan_date", "user_id", "plan_date"),
        sa.UniqueConstraint(
            "user_id", "plan_date", "kind", name="uq_plan_items_user_id_plan_date_kind"
        ),
        enum_check("kind", PlanItemKind),
        enum_check("status", PlanItemStatus),
    )
