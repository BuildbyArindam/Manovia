"""The committed API reference matches the app (Day 28).

``docs/openapi.json`` and ``docs/api.md`` are generated by
``backend/scripts/export_openapi.py``. These tests fail when a route changes and
the artifacts were not regenerated, so the published reference cannot drift from
the code it describes.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path
from types import ModuleType
from typing import cast

import pytest

from app.core.config import Settings
from app.main import create_app

_BACKEND = Path(__file__).resolve().parents[2]
_REPO = _BACKEND.parent
_SCRIPT = _BACKEND / "scripts" / "export_openapi.py"


def _load_exporter() -> ModuleType:
    spec = importlib.util.spec_from_file_location("export_openapi", _SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def exporter() -> ModuleType:
    return _load_exporter()


@pytest.fixture(scope="module")
def generated(exporter: ModuleType) -> tuple[str, str]:
    return cast(tuple[str, str], exporter.generate())


def test_committed_openapi_json_matches_the_app(generated: tuple[str, str]) -> None:
    json_text, _ = generated
    committed = (_REPO / "docs" / "openapi.json").read_text(encoding="utf-8")
    assert committed == json_text, (
        "docs/openapi.json is stale: run `cd backend && python scripts/export_openapi.py`"
    )


def test_committed_api_markdown_matches_the_app(generated: tuple[str, str]) -> None:
    _, markdown = generated
    committed = (_REPO / "docs" / "api.md").read_text(encoding="utf-8")
    assert committed == markdown, (
        "docs/api.md is stale: run `cd backend && python scripts/export_openapi.py`"
    )


def test_check_mode_reports_a_stale_file(
    exporter: ModuleType, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    stale_json = tmp_path / "openapi.json"
    stale_md = tmp_path / "api.md"
    stale_json.write_text("{}\n", encoding="utf-8")
    stale_md.write_text("old\n", encoding="utf-8")
    monkeypatch.setattr(exporter, "OPENAPI_PATH", stale_json)
    monkeypatch.setattr(exporter, "MARKDOWN_PATH", stale_md)
    monkeypatch.setattr(exporter, "REPO_DIR", tmp_path)
    assert exporter.main(["--check"]) == 1


def test_every_schema_operation_is_documented(
    exporter: ModuleType, generated: tuple[str, str]
) -> None:
    _, markdown = generated
    schema = exporter.build_schema()
    operations = [
        (path, method)
        for path, item in schema["paths"].items()
        for method in exporter.HTTP_METHODS
        if method in item
    ]
    # 63 after the Day-36 opt-in Mood Outlook route; 62 after the Day-28 removal
    # of GET /chat/sessions/{id}/stream (it put the message in the URL).
    # Update this count only when an operation is added or removed.
    assert len(operations) == 63
    for path, method in operations:
        row = f"| `{method.upper()}` | `{path}` |"
        assert row in markdown, f"missing from api.md: {method.upper()} {path}"


def test_session_requirement_is_derived_from_the_routes(exporter: ModuleType) -> None:
    app = exporter.build_app()
    sessions = exporter._session_map(app)
    schema = app.openapi()
    for path, item in schema["paths"].items():
        for method in exporter.HTTP_METHODS:
            if method in item:
                assert (path, method) in sessions, f"no session status for {method} {path}"

    assert sessions[("/api/v1/health", "get")] == "no"
    assert sessions[("/api/v1/ready", "get")] == "no"
    assert sessions[("/api/v1/auth/guest", "post")] == "no"
    assert sessions[("/api/v1/consent/requirements", "get")] == "no"
    assert sessions[("/api/v1/auth/me", "get")] == "yes"
    assert sessions[("/api/v1/privacy/export", "get")] == "yes"
    # Sending a chat message needs the signed-in user and the consent gate.
    assert sessions[("/api/v1/chat/sessions/{session_id}/messages", "post")] == "yes + consent"


def test_metrics_endpoint_is_not_in_the_published_reference(exporter: ModuleType) -> None:
    app = exporter.build_app()
    assert "/metrics" not in exporter.build_schema()["paths"]
    assert ("/metrics", "get") not in exporter._session_map(app)


def test_dev_routes_are_labelled_as_development_only(generated: tuple[str, str]) -> None:
    _, markdown = generated
    section = markdown.split("## Development only (not in production)", 1)[1]
    section = section.split("\n## ", 1)[0]
    assert "APP_ENV" in section
    assert "`/api/v1/dev/analyze`" in section


def test_production_build_has_no_dev_routes() -> None:
    from cryptography.fernet import Fernet

    settings = Settings(
        _env_file=None,
        app_env="production",
        secret_key="x" * 64,
        field_encryption_key=Fernet.generate_key().decode(),
        database_url="sqlite+aiosqlite:///:memory:",
        llm_provider="fake",
        emotion_analyzer="keyword",
        safety_ml_enabled=False,
        allowed_origins="https://app.example.test",
    )
    schema = create_app(settings).openapi()
    assert not [path for path in schema["paths"] if "/dev/" in path]


def test_rendering_is_deterministic(exporter: ModuleType) -> None:
    app = exporter.build_app()
    schema = app.openapi()
    sessions = exporter._session_map(app)
    assert exporter.render_markdown(schema, sessions) == exporter.render_markdown(schema, sessions)
